#' @title Build SVM Classifier for Axon Image Feature Classification
#' @description
#' Trains a Support Vector Machine (SVM) classifier to distinguish between degenerative
#' and intact axon states using image feature data. Supports both direct-path input
#' and interactive GUI selection.
#'
#' The feature set can either follow one of the built-in models
#' (`model = "g0.1_APA"` or `"g0.2_ACC"`) or be specified freely
#' (`model = "custom"`), which allows re-training on data acquired under a different
#' imaging system or resolution.
#'
#' @param model Character. Feature set to train on: "g0.1_APA", "g0.2_ACC", or "custom".
#'        For the two built-in sets, the hyperparameters of the built-in model are used unless
#'        `nCst` / `nGmm` are given explicitly. (default: "g0.1_APA")
#' @param features Character vector. Features to use when `model = "custom"`. Names may be
#'        given either as the short names used by the built-in models (e.g. "Ras", "ENT") or as
#'        the original EBImage column names (e.g. "s.radius.sd", "h.ent.s1"). If NULL, all
#'        available feature columns are used, except `Area` (the area weight), the centroid and
#'        orientation features (`mcx`, `mcy`, `the`), and `DVA` and `VA2`, which duplicate `CON`
#'        and `ON2`. Ignored unless
#'        `model = "custom"`. (default: NULL)
#' @param targetPixelSize Numeric or NULL. Scale, in micrometers per pixel, at which the training
#'        images were analyzed (the effective scale after resampling). It is stored with the model,
#'        and \code{\link{axQnt}} uses it as the default working scale and warns when an image is
#'        analyzed at a different scale. If NULL and the input data have a `*_Parameters.csv` file
#'        written by \code{\link{axDistmap}} in the same folder, its `PixelSize` is used when every
#'        input file is found there and all share one value. Otherwise, a message gives the reason
#'        and no scale is recorded. (default: NULL)
#' @param degenerate_path Character. Feature data for the "Degenerate" group: the path to one
#'        folder containing .txt files, or a character vector of .txt file paths. Only one
#'        folder can be specified. If NULL, a GUI folder selection dialog will be shown.
#'        (default: NULL)
#' @param intact_path Character. Feature data for the "Intact" group: the path to one folder
#'        containing .txt files, or a character vector of .txt file paths. Only one folder
#'        can be specified. If NULL, a GUI folder selection dialog will be shown.
#'        (default: NULL)
#' @param output_data_path Character or NULL. Path to save combined feature data (TSV).
#'        If NULL, a GUI save dialog will be shown.
#'        If a directory is specified, the file will be saved there with an autogenerated name.
#'        If a file name already exists, a unique name will be generated. If the directory does
#'        not exist, a warning is issued and the file is saved in the current working directory
#'        under the autogenerated name. (default: tempdir())
#' @param output_model_path Character or NULL. Path to save trained SVM model (Rdata format).
#'        If NULL, a GUI save dialog will be shown.
#'        If a directory is specified, the file will be saved there with an autogenerated name.
#'        If a file name already exists, a unique name will be generated. If the directory does
#'        not exist, a warning is issued and the file is saved in the current working directory
#'        under the autogenerated name. (default: tempdir())
#' @param nCst Numeric or NULL. SVM cost parameter (C-value) controlling margin hardness.
#'        Higher values increase model complexity. If NULL, the cost of the built-in model
#'        selected by `model` is used (1.189 for "g0.1_APA", 1.110 for "g0.2_ACC"), or 1 (the
#'        default of \code{e1071::svm}) for `model = "custom"`. (default: NULL)
#' @param nGmm Numeric or NULL. SVM gamma parameter (\eqn{\gamma}) controlling the RBF
#'        kernel width. Smaller values mean a larger kernel radius. If NULL, the gamma of the
#'        built-in model selected by `model` is used (0.0871 for "g0.1_APA", 0.207 for
#'        "g0.2_ACC"), or 0.1 for `model = "custom"`. (default: NULL)
#' @param nCrss Integer. Number of folds for cross-validation.
#'        Recommended values 5-10. (default: 5)
#' @param maxNumImg Integer or NULL. Maximum number of images (feature files) to be used from
#'        each group (Degenerate and Intact). If the number of available files in a group exceeds this
#'        value, a subset of files of size `maxNumImg` is selected randomly according to a uniform
#'        probability distribution (see `seed` and section "Sampling"). If NULL, all available files
#'        are used. The default, 12, corresponds to the number of images per group used for training
#'        the built-in models. (default: 12)
#' @param maxNumObj Integer or NULL. Maximum number of objects to be used from each image. If
#'        the number of available objects in an image exceeds this value, a subset of objects
#'        of size `maxNumObj` is selected randomly according to a uniform probability distribution
#'        (see `seed`). Because the number of objects per image varies with the degree of degeneration
#'        and/or axon density, this limit prevents a small number of images with many objects from
#'        dominating the training data. If NULL, all available objects are used. The default, 1000,
#'        corresponds to the value used for training the built-in models. (default: 1000)
#' @param seed Integer or NULL. Random seed for image and object sampling, ensuring that identical
#'        input yields identical training data. The R session's random number state is restored upon
#'        function exit. Specify a different value to assess the robustness of the model with respect
#'        to sampling variability. If NULL, no seed is set and the function uses the current random
#'        number stream. Call \code{set.seed()} beforehand for reproducibility.
#'        (default: 1)
#'
#' @return Invisibly returns the trained SVM model object and produces the following outputs:
#' \itemize{
#'   \item Combined feature data file for machine learning (TSV).
#'   \item Trained SVM model file (Rdata format)
#' }
#'
#' @details
#' The function implements a complete machine learning pipeline:
#' \enumerate{
#'   \item \strong{Input handling}: If no input paths are specified, a GUI dialog will prompt the
#'         user to select the appropriate folders. The dialog is compatible with RStudio, tcltk,
#'         and svDialogs, ensuring cross-platform support.
#'   \item \strong{Data preprocessing}: The function reads .txt files from the specified folders,
#'         using up to `maxNumImg` files per group and up to `maxNumObj` objects per file. It then merges
#'         the extracted data and assigns group labels ("Degenerate" or "Intact") to each entry.
#'         Columns that are not present in every input file (e.g. files exported with different
#'         `featureSet` settings of \code{\link{axDistmap}}) are reported and not used.
#'   \item \strong{Name conversion}: \code{\link{axDistmap}} exports short feature names used by the
#'         built-in models (e.g., Ras, ENT). If columns still use the original EBImage names, these are
#'         converted to the corresponding short names (e.g., s.radius.sd -> Ras) prior to training.
#'   \item \strong{Feature selection}: Feature selection is restricted to those specified in `model` or `features`.
#'   \item \strong{Model training and evaluation}: Model training and evaluation are performed using
#'         the e1071 package with a radial basis function (RBF) kernel. Cross-validation is applied.
#'   \item \strong{Result saving}: The merged feature data and the trained SVM model are exported to disk.
#'         Unique filenames are generated automatically to prevent overwriting.
#' }
#'
#' @section Sampling:
#' With an integer seed, the random number generator is initialized using
#' \code{set.seed(seed, kind = "Mersenne-Twister", normal.kind = "Inversion", sample.kind = "Rejection")}
#' prior to sampling. This ensures that identical input always produces identical training data, and the
#' original random number state of the R session is restored upon function exit. Before sampling, files
#' within each group are sorted in a locale-independent manner, guaranteeing that file selection is
#' consistent across operating systems. Sampling proceeds by selecting images first (Degenerate group,
#' then Intact group), followed by objects within each file. Within each file, objects retain their
#' original order. For each group, the numbers of available and selected images and objects are reported.
#'
#'
#' @section GUI Support:
#' \itemize{
#'   \item RStudio (rstudioapi), tcltk and svDialogs are supported for file/folder selection.
#'   \item If no GUI is available, the input paths must be given as arguments; output paths can be entered manually.
#' }
#'
#' @section Built-in feature sets:
#' \itemize{
#'   \item \strong{g0.1 APA} (5 features): Ras, ENT, Per, SVA, SV2;
#'         gamma = 0.0871, cost = 1.189. Recommended primary model.
#'   \item \strong{g0.2 ACC} (6 features): CON, ecc, mjx, cir, Ras, Ran;
#'         gamma = 0.207, cost = 1.110.
#' }
#'
#' @note
#' \itemize{
#'   \item Compatible with feature data from \code{\link{axDistmap}}
#'   \item Default output file names include a timestamp in ISO 8601 format (YYYY-MM-DD)
#'   \item Model files can be reloaded using base::load()
#'   \item Models produced here can be applied directly with \code{\link{axQnt}}, which reads the
#'         required predictors from the model object itself.
#' }
#'
#' @examples
#' # Interactive mode with GUI prompts
#' # NOTE: This example requires a GUI environment for interactive folder selection.
#' if (interactive()){
#' axSvm()
#' }
#'
#' \donttest{
#' # Re-train the g0.1 APA feature set on your own data
#' deg_dir <- system.file("extdata", "Degenerate_txt", package = "AiES")
#' int_dir <- system.file("extdata", "Intact_txt", package = "AiES")
#' axSvm(model = "g0.1_APA", degenerate_path = deg_dir, intact_path = int_dir,
#'       output_data_path = tempdir(), output_model_path = tempdir())
#'
#' # Train on a freely chosen feature set with custom hyperparameters
#' axSvm(model = "custom", features = c("Ras", "ENT", "cir"),
#'       nCst = 5, nGmm = 0.05, nCrss = 10,
#'       degenerate_path = deg_dir, intact_path = int_dir,
#'       output_data_path = tempdir(), output_model_path = tempdir())
#' }
#'
#' @importFrom data.table fread rbindlist fwrite
#' @importFrom e1071 svm
#'
#' @export
axSvm <- function(model = "g0.1_APA",
                  features = NULL,
                  targetPixelSize = NULL,
                  nCst = NULL, nGmm = NULL, nCrss = 5,
                  maxNumImg = 12,       # same as the built-in models
                  maxNumObj = 1000,     # same as the built-in models
                  seed = 1,
                  degenerate_path = NULL,
                  intact_path = NULL,
                  output_data_path = tempdir(),
                  output_model_path = tempdir()
){

    ##############Definition of variable######################

    model <- match.arg(model, c(names(.aiesModels), "custom"))

    ## Resolve hyperparameters from the preset unless given explicitly
    if (model != "custom") {
        preset <- .aiesModels[[model]]
        if (is.null(nGmm)) nGmm <- preset$gamma
        if (is.null(nCst)) nCst <- preset$cost
    } else {
        if (is.null(nGmm)) nGmm <- 0.1
        if (is.null(nCst)) nCst <- 1
    }

    ## Sampling limits: NULL (use all) or a positive integer
    check_max <- function(x, nm) {
        if (is.null(x)) return(NULL)
        if (length(x) != 1 || !is.numeric(x) || is.na(x) || x < 1 || x != round(x)) {
            stop("`", nm, "` must be NULL or a positive integer.", call. = FALSE)
        }
        as.integer(x)
    }
    maxNumImg <- check_max(maxNumImg, "maxNumImg")
    maxNumObj <- check_max(maxNumObj, "maxNumObj")

    ## Seed for image and object sampling (reproducibility). With an integer seed,
    ## the caller's random number state is restored on exit; with NULL it is left
    ## to the session (no seed is set).
    if (!is.null(seed)) {
        if (length(seed) != 1 || !is.numeric(seed) || !is.finite(seed) || seed != round(seed)) {
            stop("`seed` must be NULL or a single integer.", call. = FALSE)
        }
        seed <- as.integer(seed)
        if (exists(".Random.seed", envir = globalenv(), inherits = FALSE)) {
            oldSeed <- get(".Random.seed", envir = globalenv(), inherits = FALSE)
            on.exit(assign(".Random.seed", oldSeed, envir = globalenv()), add = TRUE)
        } else {
            on.exit(if (exists(".Random.seed", envir = globalenv(), inherits = FALSE))
                rm(".Random.seed", envir = globalenv()), add = TRUE)
        }
    }

    ###############Definition of function######################
    ##Function 1 Folder selection
    select_folder <- function(caption = "Select folder") {
        if (rstudioapi::isAvailable()) {
            return(rstudioapi::selectDirectory(caption = caption))
        } else if (requireNamespace("tcltk", quietly = TRUE)) {
            return(tcltk::tk_choose.dir(caption = caption))
        } else if (requireNamespace("svDialogs", quietly = TRUE)) {
            return(svDialogs::dlg_dir(title = caption)$res)
        } else {
            message("No GUI folder selection method available")
            return(NULL)
        }
    }

    ##Function 2 Function to avoid duplicate file names
    generate_unique_filename <- function(filepath) {
        if (!file.exists(filepath)) return(filepath)
        base <- sub("(\\.[^.]*)$", "", filepath)   # before extension
        ext <- sub("^.*(\\.[^.]*)$", "\\1", filepath) # extension
        i <- 1
        new_filepath <- paste0(base, "_", i, ext)
        while (file.exists(new_filepath)) {
            i <- i + 1
            new_filepath <- paste0(base, "_", i, ext)
        }
        return(new_filepath)
    }

    ##Function 3 Function to specify output path
    output_path <- function(path, default_name, select_save_file_fun, caption = "Save file as") {
        if (is.null(path)) {
            resolved <- select_save_file_fun(default_name, caption = caption)
            if (is.null(resolved) || resolved == "") return(NULL)
            path <- resolved
        }
        if (dir.exists(path)) {
            path <- file.path(path, default_name)
            path <- generate_unique_filename(path)
        } else if (file.exists(path)) {
            path <- generate_unique_filename(path)
        } else {
            folder_part <- dirname(path)
            if (!dir.exists(folder_part)) {
                warning(sprintf("Directory '%s' does not exist. Saving to current directory.", folder_part))
                path <- generate_unique_filename(default_name)
            }
        }
        return(path)
    }

    # 1. Obtain input data
    ## One folder (its .txt files are used) or a character vector of .txt files.
    ## Several folders, or folders mixed with files, are not accepted.
    resolve_input <- function(path, argName) {
        if (!is.character(path) || length(path) == 0 || anyNA(path)) {
            stop("`", argName, "` must be one folder or a character vector of .txt files.",
                 call. = FALSE)
        }
        isDir <- dir.exists(path)
        if (any(isDir)) {
            if (length(path) > 1) {
                stop("`", argName, "`: only one folder can be specified. ",
                     "To combine several folders, pass their .txt files as a character vector.",
                     call. = FALSE)
            }
            return(list.files(path, pattern = "\\.txt$", full.names = TRUE))
        }
        path
    }

    if (is.null(degenerate_path)) {
        message("Select folder for Degenerate condition")
        degenerate_path <- select_folder("Select Degenerate folder")
        if (is.null(degenerate_path) || is.na(degenerate_path)) return(message("No folder selected."))
    }
    degenerate_files <- resolve_input(degenerate_path, "degenerate_path")
    if (length(degenerate_files) == 0) return(message("No degenerate files found."))

    if (is.null(intact_path)) {
        message("Select folder for Intact condition")
        intact_path <- select_folder("Select Intact folder")
        if (is.null(intact_path) || is.na(intact_path)) return(message("No folder selected."))
    }
    intact_files <- resolve_input(intact_path, "intact_path")
    if (length(intact_files) == 0) return(message("No intact files found."))

    ## Image sampling: For each group, up to maxNumImg files are selected. Before selection, files
    ## are sorted in a locale-independent order to ensure consistent results across all operating systems.
    if (!is.null(seed)) {
        set.seed(seed, kind = "Mersenne-Twister",
                 normal.kind = "Inversion", sample.kind = "Rejection")
    }
    pick_files <- function(files) {
        files <- sort(unique(files), method = "radix")
        if (!is.null(maxNumImg) && length(files) > maxNumImg) {
            files <- sort(sample(files, maxNumImg), method = "radix")
        }
        files
    }
    nImgAll <- c(Degenerate = length(unique(degenerate_files)),
                 Intact     = length(unique(intact_files)))
    degenerate_files <- pick_files(degenerate_files)
    intact_files     <- pick_files(intact_files)


    ## Training scale from the *_Parameters.csv written by axDistmap() next to each
    ## ImageData.txt (rows matched through DataFile). Returns NULL, with a message
    ## giving the reason, unless every file is found with one common finite PixelSize.
    read_train_scale <- function(files) {
        files <- unique(files)
        ps <- rep(NA_real_, length(files))
        found <- FALSE
        for (d in unique(dirname(files))) {
            pfiles <- list.files(d, pattern = "_Parameters\\.csv$", full.names = TRUE)
            if (length(pfiles) == 0) next
            tab <- do.call(rbind, lapply(pfiles, function(pf) {
                t <- tryCatch(as.data.frame(data.table::fread(pf)), error = function(e) NULL)
                if (is.null(t) || !all(c("DataFile", "PixelSize") %in% colnames(t))) return(NULL)
                t[, c("DataFile", "PixelSize")]
            }))
            if (is.null(tab)) next
            found <- TRUE
            idx <- which(dirname(files) == d)
            hit <- match(basename(files[idx]), tab$DataFile)
            ps[idx] <- suppressWarnings(as.numeric(tab$PixelSize[hit]))
        }
        if (!found) {
            message("Parameter file (*_Parameters.csv) could not be found or read next to the input data. ",
                    "Training scale is not recorded with the model.")
            return(NULL)
        }
        if (anyNA(ps)) {
            message("Parameter file: PixelSize is missing for ", sum(is.na(ps)), " of ", length(ps),
                    " input files (not listed or scale unknown). Training scale is not recorded.")
            return(NULL)
        }
        u <- unique(round(ps, 6))
        if (length(u) > 1) {
            message("Input data mix ", length(u), " different pixel sizes (",
                    paste(sprintf("%.4f", range(u)), collapse = " - "),
                    " um/px). Training scale is not recorded.")
            return(NULL)
        }
        u
    }

    # 2. Data reading (large-scale support)
    ## Object sampling: For each file, up to maxNumObj objects are selected in their
    ## original file order. The random number stream initialized during image sampling is
    ## continued for object sampling.
    ## Columns are converted to short names file by file (files written by earlier
    ## versions carry EBImage names), and the column names of every file read are kept
    ## in fileCols for the consistency check below.
    fileCols <- list()
    read_data <- function(files, group) {
        nObjAll <- 0
        datalist <- lapply(files, function(f) {
            dt <- tryCatch(data.table::fread(f), error = function(e) NULL)
            if (is.null(dt)) return(NULL)
            dt <- .aiesToShort(as.data.frame(dt))
            fileCols[[f]] <<- colnames(dt)
            nObjAll <<- nObjAll + nrow(dt)
            if (!is.null(maxNumObj) && nrow(dt) > maxNumObj) {
                dt <- dt[sort(sample.int(nrow(dt), maxNumObj)), ]
            }
            dt$Group <- group
            dt
        })
        datalist <- datalist[!sapply(datalist, is.null)]
        if (length(datalist) == 0) return(NULL)
        out <- data.table::rbindlist(datalist, fill = TRUE)
        message(sprintf("%s: %d of %d images (%d read), %d of %d objects used",
                        group, length(files), nImgAll[[group]], length(datalist),
                        nrow(out), nObjAll))
        out
    }
    message("Sampling: maxNumImg = ", if (is.null(maxNumImg)) "all" else maxNumImg,
            ", maxNumObj = ", if (is.null(maxNumObj)) "all" else maxNumObj,
            " (per image), seed = ", if (is.null(seed)) "not set" else seed)
    deg_data <- read_data(degenerate_files, "Degenerate")
    intact_data <- read_data(intact_files, "Intact")
    if (is.null(deg_data) || is.null(intact_data)) return(message("Failed to read data."))


    # 3. Data merging, column check and feature selection
    dataSvm <- as.data.frame(data.table::rbindlist(list(deg_data, intact_data), fill = TRUE))
    rm(deg_data, intact_data); gc()

    ## Every input file must have the same columns. Columns missing from some files
    ## (e.g. files exported with different featureSet settings) would be filled with NA,
    ## and the affected objects silently dropped by svm(); they are reported and not used.
    commonCols <- Reduce(intersect, fileCols)
    partCols   <- setdiff(unique(unlist(fileCols)), commonCols)
    if (length(partCols) > 0) {
        nLack <- vapply(partCols, function(cl)
            sum(!vapply(fileCols, function(x) cl %in% x, logical(1))), integer(1))
        message("Columns not present in every input file (not used): ",
                paste0(partCols, " (missing in ", nLack, " of ", length(fileCols), " files)",
                       collapse = ", "),
                "\n  The input files were probably exported with different settings ",
                "(e.g. featureSet = \"standard\" and \"all\" in axDistmap).")
        dataSvm <- dataSvm[, setdiff(colnames(dataSvm), partCols), drop = FALSE]
    }

    ## Resolve the feature set
    if (model != "custom") {
        ftrTmp <- .aiesModels[[model]]$features
    } else if (!is.null(features)) {
        ftrTmp <- .aiesAsShort(features)
    } else {
        ## everything except the grouping variable, the area weight and uninformative features
        ## (see .aiesNonFeature)
        ftrTmp <- setdiff(colnames(dataSvm), .aiesNonFeature)
    }

    missing_ftr <- setdiff(ftrTmp, colnames(dataSvm))
    if (length(missing_ftr) > 0) {
        inPart <- missing_ftr %in% partCols
        return(message("Required features missing from the input data: ",
                       paste0(missing_ftr, ifelse(inPart, " (present in only some files)", ""),
                              collapse = ", "),
                       "\n  Available in every file: ",
                       paste(setdiff(colnames(dataSvm), "Group"), collapse = ", ")))
    }

    message("Training '", model, "' with ", length(ftrTmp), " features: ",
            paste(ftrTmp, collapse = ", "))
    message("  gamma = ", nGmm, ", cost = ", nCst, ", cross = ", nCrss)

    ## Physical scale of the training data (source information for axQnt)
    if (!is.null(targetPixelSize)) {
        message("  training scale: ", sprintf("%.6f", targetPixelSize), " um/px (argument)")
    } else {
        targetPixelSize <- read_train_scale(c(degenerate_files, intact_files))
        if (!is.null(targetPixelSize)) {
            message("  training scale: ", sprintf("%.6f", targetPixelSize),
                    " um/px (from *_Parameters.csv)")
        }
    }

    dataSvm <- dataSvm[, c("Group", ftrTmp), drop = FALSE]
    dataSvm$Group <- as.factor(dataSvm$Group)


    # 4. SVM model construction
    svmModel <- e1071::svm(
        Group ~ .,
        data = dataSvm,
        method = "C-classification",
        probability = TRUE,
        kernel = "radial",
        gamma = nGmm,
        cost = nCst,
        cross = nCrss
    )

    ## Record which feature set this model represents (used by axQnt for reporting)
    attr(svmModel, "aiesModel") <- model
    attr(svmModel, "aiesPixelSize") <- targetPixelSize

    # 5. Specify output file
    select_save_file <- function(default_name = "output.txt", caption = "Save file as") {
        if (requireNamespace("rstudioapi", quietly = TRUE) && rstudioapi::isAvailable()) {
            path <- rstudioapi::selectFile(caption = caption, path = default_name, label = "Save", existing = FALSE)
            if (!is.null(path) && path != "") return(path)
        }
        if (requireNamespace("tcltk", quietly = TRUE)) {
            path <- tcltk::tclvalue(tcltk::tkgetSaveFile(initialfile = default_name, title = caption))
            if (!is.null(path) && path != "") return(path)
        }
        if (requireNamespace("svDialogs", quietly = TRUE)) {
            path <- svDialogs::dlg_save(default = default_name, title = caption)$res
            if (!is.null(path) && path != "") return(path)
        }
        cat(sprintf("Please enter the full path to save the file [%s]: ", default_name))
        path <- readline()
        if (path == "") path <- default_name
        return(path)
    }


    # Output data file save location
    default_data_name <- paste0(Sys.Date(), "_Extracted_data_for_ML.txt")
    output_data_path <- output_path(
        output_data_path,
        default_data_name,
        select_save_file,
        caption = "Save extracted data file"
    )
    if (is.null(output_data_path) || output_data_path == "") return(message("Canceled"))
    data.table::fwrite(dataSvm, file = output_data_path, sep = "\t")
    message("Extracted data saved: ", output_data_path)

    # Model file save location
    default_model_name <- paste0(Sys.Date(), "_AxClassifier.svm")
    output_model_path <- output_path(
        output_model_path,
        default_model_name,
        select_save_file,
        caption = "Save SVM model"
    )
    if (is.null(output_model_path) || output_model_path == "") return(message("Canceled"))
    save(svmModel, file = output_model_path)
    message("SVM model saved: ", output_model_path)


    invisible(svmModel)

}###end of function
